uint64_t HertzTicksToFileTime(uint64_t nanoseconds)
{
    static const long hertz = sysconf(_SC_CLK_TCK);
    const uint64_t perTick = 1000000000ull / static_cast<uint64_t>(hertz > 0 ? hertz : 100);
    return LinuxBootFileTime() + (nanoseconds / perTick) * (10000000ull / static_cast<uint64_t>(hertz > 0 ? hertz : 100));
}

/* A CLOCK_BOOTTIME stamp as FILETIME on the realtime clock. */
uint64_t BootToFileTime(uint64_t bootNanoseconds)
{
    timespec boot{}, real{};
    clock_gettime(CLOCK_BOOTTIME, &boot);
    clock_gettime(CLOCK_REALTIME, &real);
    const int64_t bootNow = static_cast<int64_t>(boot.tv_sec) * 1000000000ll + boot.tv_nsec;
    const int64_t realNow = static_cast<int64_t>(real.tv_sec) * 1000000000ll + real.tv_nsec;
    const int64_t at = realNow - (bootNow - static_cast<int64_t>(bootNanoseconds));
    return MSMON_UNIX_EPOCH_AS_FILETIME + static_cast<uint64_t>(at / 100);
}

std::wstring Text(const char* value, size_t capacity)
{
    return LinuxWide(std::string(value, strnlen(value, capacity)));
}

std::wstring Hex(uint64_t value)
{
    wchar_t text[24];
    swprintf(text, 24, L"0x%llx", static_cast<unsigned long long>(value));
    return text;
}

std::wstring Join(const std::wstring& directory, const std::wstring& name)
{
    if (name.empty() || name[0] == L'/' || directory.empty()) return name;
    return directory + (directory.back() == L'/' ? L"" : L"/") + name;
}

/* The kernel path of the record's file, with pipes, sockets and anonymous inodes named. */
std::wstring FilePath(const mm_event& e)
{
    if ((e.flags & MM_F_KPATH) == 0) return {};
    std::wstring path = Text(e.kpath, sizeof(e.kpath));
    if (path == L"/" && !S_ISDIR(e.mode)) {
        const wchar_t* kind = S_ISSOCK(e.mode) ? L"socket" : S_ISFIFO(e.mode) ? L"pipe" : L"anon_inode";
        path = std::wstring(kind) + L":[" + std::to_wstring(e.ino) + L"]";
    }
    return path;
}

std::wstring Endpoint(const mm_event& e, unsigned& family, uint16_t& port)
{
    family = 0;
    port = 0;
    if ((e.flags & MM_F_SOCK) == 0 || e.sock_len < 2) return {};
    sa_family_t value = 0;
    std::memcpy(&value, e.path_b, sizeof(value));
    family = value;
    char text[INET6_ADDRSTRLEN]{};
    if (value == AF_INET && e.sock_len >= sizeof(sockaddr_in)) {
        sockaddr_in address{};
        std::memcpy(&address, e.path_b, sizeof(address));
        port = ntohs(address.sin_port);
        inet_ntop(AF_INET, &address.sin_addr, text, sizeof(text));
        return LinuxWide(text) + L":" + std::to_wstring(port);
    }
    if (value == AF_INET6 && e.sock_len >= sizeof(sockaddr_in6)) {
        sockaddr_in6 address{};
        std::memcpy(&address, e.path_b, sizeof(address));
        port = ntohs(address.sin6_port);
        inet_ntop(AF_INET6, &address.sin6_addr, text, sizeof(text));
        return L"[" + LinuxWide(text) + L"]:" + std::to_wstring(port);
    }
    if (value == AF_UNIX) {
        const size_t length = std::min<size_t>(e.sock_len, sizeof(e.path_b)) - offsetof(sockaddr_un, sun_path);
        const char* name = e.path_b + offsetof(sockaddr_un, sun_path);
        if (length == 0) return L"unix:unnamed";
        /* An abstract name starts with a NUL byte. */
        if (name[0] == '\0') return L"unix:@" + LinuxWide(std::string(name + 1, strnlen(name + 1, length - 1)));
        return L"unix:" + LinuxWide(std::string(name, strnlen(name, length)));
    }
    return L"family=" + std::to_wstring(value);
}

std::wstring Argv(const mm_event& e)
{
    std::wstring line;
    for (unsigned slot = 0; slot < MM_ARGV_SLOTS; slot++) {
        const char* arg = e.path_b + slot * MM_ARGV_SLOT;
        if (arg[0] == '\0') break;
        if (!line.empty()) line += L' ';
        line += Text(arg, MM_ARGV_SLOT);
    }
    return line;
}

void Record(const mm_event& e, unsigned sensor, ULONG type, uint64_t value0, uint64_t value1,
            const std::wstring& text, const std::wstring& detail, ULONG flags, DWORD target = 0)
{
    LinuxRecord record;
    record.sensor = sensor;
    record.type = type;
    record.pid = e.tgid;
    record.tid = e.tid;
    record.start = HertzTicksToFileTime(e.start_ns);
    record.flags = flags;
    record.timestamp = BootToFileTime(e.ts_ns);
    record.status = e.ret < 0 ? static_cast<long>(e.ret) : 0;
    record.target = target;
    record.value0 = value0;
    record.value1 = value1;
    record.text = text;
    record.detail = detail;
    record.stack.assign(e.stack, e.stack + std::min<uint32_t>(e.frames, MM_FRAMES));
    gBpf.session->Write(record);
}

void OnSyscall(const mm_event& e)
{
    if (e.nr >= MM_SYSCALLS || gBpf.byNumber[e.nr] == nullptr) return;
    const Syscall& call = *gBpf.byNumber[e.nr];
    LinuxSession& session = *gBpf.session;
    uint64_t start = 0;
    ULONG trackFlags = 0;
    if (!session.Tracked(e.tgid, start, trackFlags)) return;

    std::wstring detail = L"syscall=" + LinuxWide(call.name) + L";ret=" + std::to_wstring(e.ret) +
                          L";dur_ns=" + std::to_wstring(e.dur_ns) + L";args=";
    for (unsigned index = 0; index < 6; index++) detail += (index != 0 ? L"," : L"") + Hex(e.args[index]);
    const uint64_t fdKey = (static_cast<uint64_t>(e.tgid) << 32) | static_cast<uint32_t>(e.args[0]);
    std::wstring file = FilePath(e);
    if (file.empty() && call.info.fd == 1) {
        auto known = gBpf.fds.find(fdKey);
        if (known != gBpf.fds.end()) file = known->second;
    }
    const std::wstring pathA = Join(Text(e.kdir_a, sizeof(e.kdir_a)), Text(e.path_a, sizeof(e.path_a)));
    const std::wstring pathB = (e.flags & (MM_F_SOCK | MM_F_ARGV)) != 0
                                   ? std::wstring()
                                   : Join(Text(e.kdir_b, sizeof(e.kdir_b)), Text(e.path_b, sizeof(e.path_b)));
    ULONG flags = 0;
    if ((e.flags & (MM_F_TRUNC_A | MM_F_TRUNC_K)) != 0) flags |= MsMonFlagTruncatedPath;
    auto missing = [&](const std::wstring& path) { return path.empty() ? static_cast<ULONG>(MsMonFlagMissingPath) : 0u; };
    const bool socketFd = S_ISSOCK(e.mode);
    const bool success = e.ret >= 0;
    unsigned family = 0;
    uint16_t port = 0;
    const std::wstring endpoint = Endpoint(e, family, port);
    const unsigned netSensor = family == AF_UNIX ? MSMON_SENSOR_LINUX_EBPF_IPC : MSMON_SENSOR_LINUX_EBPF_NET;
    const unsigned fileSensor = socketFd ? MSMON_SENSOR_LINUX_EBPF_NET : MSMON_SENSOR_LINUX_EBPF_FILE;
    const uint64_t offset = (e.nr == SYS_pread64 || e.nr == SYS_pwrite64 || e.nr == SYS_preadv || e.nr == SYS_pwritev ||
                             e.nr == SYS_preadv2 || e.nr == SYS_pwritev2)
                                ? e.args[3]
                                : e.pos;

    switch (call.op) {
    case Op::Read:
    case Op::Write:
        Record(e, fileSensor, call.op == Op::Read ? MsMonFileRead : MsMonFileWrite, success ? e.ret : 0, offset, file,
               detail + L";requested=" + std::to_wstring(e.args[2]), flags | missing(file));
        break;
    case Op::Open: {
        const std::wstring path = !file.empty() ? file : pathA;
        if (success && !path.empty()) gBpf.fds[(static_cast<uint64_t>(e.tgid) << 32) | static_cast<uint32_t>(e.ret)] = path;
        const uint64_t openFlags = e.nr == SYS_open ? e.args[1] : e.nr == SYS_creat ? 0x241 : e.args[2];
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileCreate, openFlags, success ? e.ret : 0, path,
               detail + L";open_flags=" + Hex(openFlags) + (pathA != path && !pathA.empty() ? L";requested=" + pathA : L""),
               flags | missing(path));
        break;
    }
    case Op::Close:
        gBpf.fds.erase(fdKey);
        if (socketFd) {
            Record(e, MSMON_SENSOR_LINUX_EBPF_NET, MsMonNetworkFlowClose, e.ino, 0, file, L"close;" + detail, flags);
        } else {
            Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileClose, 0, 0, file, detail, flags | missing(file));
        }
        break;
    case Op::Query: {
        const std::wstring path = !pathA.empty() ? pathA : file;
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileQueryInformation, e.nr, 0, path, detail, flags | missing(path));
        break;
    }
    case Op::Directory:
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileDirectoryControl, 1, success ? e.ret : 0, file, detail,
               flags | missing(file));
        break;
    case Op::Unlink: {
        const bool directory = e.nr == SYS_rmdir || (e.nr == SYS_unlinkat && (e.args[2] & 0x200) != 0);
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileSetInformation, FILE_DISPOSITION_INFORMATION, 0, pathA,
               (directory ? L"unlink;directory;" : L"unlink;") + detail, flags | missing(pathA));
        break;
    }
    case Op::Rename:
        /* Two records, as the fanotify sensor writes them: the old name, then the new one. */
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileSetInformation, FILE_RENAME_INFORMATION, 0, pathA,
               L"rename;from;" + detail, flags | missing(pathA));
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileSetInformation, FILE_RENAME_INFORMATION, 0, pathB,
               L"rename;to;" + detail, missing(pathB));
        break;
    case Op::Link:
    case Op::Symlink:
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileSetInformation, FILE_LINK_INFORMATION, 0, pathB,
               std::wstring(call.op == Op::Link ? L"link" : L"symlink") + L";target=" + pathA + L";" + detail,
               missing(pathB));
        break;
    case Op::Mkdir:
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileCreate, CREATE_DISPOSITION_CREATE, 0, pathA,
               LinuxWide(call.name) + L";" + detail, flags | missing(pathA));
        break;
    case Op::Truncate: {
        const std::wstring path = !pathA.empty() ? pathA : file;
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileSetInformation, FILE_END_OF_FILE_INFORMATION,
               e.nr == SYS_fallocate ? e.args[3] : e.args[1], path, detail, flags | missing(path));
        break;
    }
    case Op::Security: {
        const std::wstring path = !pathA.empty() ? pathA : file;
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, MsMonFileSetSecurity, e.args[1], e.args[2], path, detail,
               flags | missing(path));
        break;
    }
    case Op::SetEa:
    case Op::QueryEa: {
        const std::wstring path = !pathA.empty() ? pathA : file;
        Record(e, MSMON_SENSOR_LINUX_EBPF_FILE, call.op == Op::SetEa ? MsMonFileSetEa : MsMonFileQueryEa, 0, 0, path,
               detail, flags | missing(path));
        break;
    }
    case Op::Ioctl:
        Record(e, MSMON_SENSOR_LINUX_EBPF_DEVICE, MsMonFileDeviceControl, e.args[1], e.args[2], file, detail,
               flags | missing(file));
        break;
    case Op::Mmap: {
        const bool fileBacked = (e.flags & MM_F_KPATH) != 0 && static_cast<int>(e.args[4]) >= 0;
        const bool executable = (e.args[2] & 0x4) != 0;   // PROT_EXEC
        if (!fileBacked && !executable) break;
        const std::wstring text = fileBacked ? file : L"anonymous";
        Record(e, MSMON_SENSOR_LINUX_EBPF_MEMORY, MsMonFileSection, e.args[3], e.args[2], text, detail, flags);
        /* The poll owns image_load (it also sees Wine's mprotect(PROT_EXEC) images); rescan
         * now so a stack right after the mapping resolves without waiting for the tick. */
        if (fileBacked && executable && success) ImagesScan(session, e.tgid, start);
        break;
    }
    case Op::Mprotect:
        if ((e.args[2] & 0x4) == 0) break;
        Record(e, MSMON_SENSOR_LINUX_EBPF_MEMORY, MsMonFileSection, 0, e.args[2], L"mprotect:" + Hex(e.args[0]),
               detail, 0);
        if (success) ImagesScan(session, e.tgid, start);
        break;
    case Op::Ptrace:
        Record(e, MSMON_SENSOR_LINUX_EBPF_MEMORY, MsMonProcessHandle, e.args[0], e.args[2], {}, L"ptrace;" + detail, 0,
               static_cast<DWORD>(e.args[1]));
        break;
    case Op::VmRead:
    case Op::VmWrite:
        Record(e, MSMON_SENSOR_LINUX_EBPF_MEMORY, MsMonProcessHandle, call.op == Op::VmRead ? 1 : 2,
               success ? e.ret : 0, {}, LinuxWide(call.name) + L";" + detail, 0, static_cast<DWORD>(e.args[0]));
        break;
    case Op::Signal: {
        const uint64_t signal = e.nr == SYS_tgkill ? e.args[2] : e.args[1];
        Record(e, MSMON_SENSOR_LINUX_EBPF_IPC, MsMonProcessHandle, 0, signal, {},
               L"signal=" + std::to_wstring(signal) + L";" + detail, 0, static_cast<DWORD>(e.args[0]));
        break;
    }
    case Op::Connect:
        Record(e, netSensor, MsMonNetworkConnect, e.ino, port, endpoint,
               L"connect;family=" + std::to_wstring(family) + L";" + detail, endpoint.empty() ? MsMonFlagMissingPath : 0);
        break;
    case Op::Accept:
        if (success) gBpf.fds[(static_cast<uint64_t>(e.tgid) << 32) | static_cast<uint32_t>(e.ret)] = L"socket:" + endpoint;
        Record(e, netSensor, MsMonNetworkAccept, e.ino, port, endpoint,
               L"accept;family=" + std::to_wstring(family) + L";" + detail, 0);
        break;
    case Op::SendTo:
    case Op::RecvFrom:
        if (!endpoint.empty()) {
            Record(e, netSensor, call.op == Op::SendTo ? MsMonNetworkConnect : MsMonNetworkAccept, e.ino, port, endpoint,
                   std::wstring(call.op == Op::SendTo ? L"sendto" : L"recvfrom") + L";family=" + std::to_wstring(family) +
                       L";bytes=" + std::to_wstring(success ? e.ret : 0) + L";" + detail,
                   0);
        } else {
            Record(e, fileSensor, call.op == Op::SendTo ? MsMonFileWrite : MsMonFileRead, success ? e.ret : 0, 0, file,
                   detail, flags | missing(file));
        }
        break;
    case Op::Exec:
        /* Only a failed exec reaches here; a successful one is the MM_EXEC record. */
        Record(e, MSMON_SENSOR_LINUX_EBPF_PROCESS, MsMonProcessStart, start, 2, pathA, L"exec_failed;" + detail,
               flags | missing(pathA));
        break;
    }
}

void OnRecord(const mm_event& e)
{
    LinuxSession& session = *gBpf.session;
    switch (e.kind) {
    case MM_SYSCALL:
        session.Enter(MSMON_SENSOR_LINUX_EBPF_FILE);
        OnSyscall(e);
        break;
    case MM_FORK:
    case MM_SCOPE: {
        session.Enter(MSMON_SENSOR_LINUX_EBPF_PROCESS);
        const uint64_t start = HertzTicksToFileTime(e.start_ns);
        const ULONG flags = e.kind == MM_FORK ? MsMonFlagInheritedTrack : MsMonFlagExplicitTrack;
        uint64_t known = 0;
        ULONG knownFlags = 0;
        if (session.Tracked(e.tgid, known, knownFlags) && known == start) break;
        if (!session.Admit(e.tgid, start, flags)) break;
        std::wstring image;
        uint64_t ignored = 0;
        (void)LinuxProcessIdentity(e.tgid, image, ignored);
        Record(e, MSMON_SENSOR_LINUX_EBPF_PROCESS, MsMonProcessStart, start, 0, image,
               ProcessCommandLine(e.tgid) + (e.kind == MM_SCOPE ? L";scope=exec_mapping:" + FilePath(e) : L""), flags);
        ImagesScan(session, e.tgid, start);
        break;
    }
    case MM_EXEC: {
        session.Enter(MSMON_SENSOR_LINUX_EBPF_PROCESS);
        uint64_t start = 0;
        ULONG flags = 0;
        if (!session.Tracked(e.tgid, start, flags)) break;
        const std::wstring image = !FilePath(e).empty() ? FilePath(e) : Text(e.path_a, sizeof(e.path_a));
        Record(e, MSMON_SENSOR_LINUX_EBPF_PROCESS, MsMonProcessStart, start, 1, image,
               (e.flags & MM_F_ARGV) != 0 ? Argv(e) : ProcessCommandLine(e.tgid), flags);
        ImagesScan(session, e.tgid, start);
        break;
    }
    case MM_EXIT: {
        session.Enter(MSMON_SENSOR_LINUX_EBPF_PROCESS);
        uint64_t start = 0;
        ULONG flags = 0;
        if (!session.Tracked(e.tgid, start, flags)) break;
        Record(e, MSMON_SENSOR_LINUX_EBPF_PROCESS, MsMonProcessExit, start, 0, {}, {}, 0);
        session.Forget(e.tgid, start);
        ImagesForget(e.tgid);
        for (auto it = gBpf.fds.begin(); it != gBpf.fds.end();) {
            it = (it->first >> 32) == e.tgid ? gBpf.fds.erase(it) : std::next(it);
        }
        break;
    }
    case MM_THREAD_START:
    case MM_THREAD_EXIT: {
        session.Enter(MSMON_SENSOR_LINUX_EBPF_PROCESS);
        uint64_t start = 0;
        ULONG flags = 0;
        if (!session.Tracked(e.tgid, start, flags)) break;
        Record(e, MSMON_SENSOR_LINUX_EBPF_PROCESS, e.kind == MM_THREAD_START ? MsMonThreadStart : MsMonThreadExit,
               e.tid, 0, {}, {}, 0);
        break;
    }
    case MM_DENIED: {
        static const wchar_t* names[] = {L"", L"ptrace", L"bpf", L"perf_event_open"};
        const wchar_t* name = e.nr < 4 ? names[e.nr] : L"unknown";
        Record(e, MSMON_SENSOR_LINUX_EBPF_MEMORY, MsMonProcessHandle, e.nr, 0, {},
               L"self_protection_denied=" + std::wstring(name), 0, e.target_tgid);
        break;
    }
    default:
        break;
    }
}

int OnRing(void*, void* data, size_t size)
{
    if (size >= sizeof(mm_event)) OnRecord(*static_cast<const mm_event*>(data));
    return 0;
}

int PrintLibbpf(enum libbpf_print_level level, const char* format, va_list args)
{
    if (level == LIBBPF_DEBUG) return 0;
    return vfprintf(stderr, format, args);
}

